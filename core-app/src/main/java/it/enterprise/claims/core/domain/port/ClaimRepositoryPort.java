package it.enterprise.claims.core.domain.port;

import it.enterprise.claims.core.domain.model.Claim;
import it.enterprise.claims.core.domain.model.ClaimStatus;
import it.enterprise.claims.core.domain.model.ClaimStatusHistory;
import java.util.List;
import java.util.Optional;
import java.util.UUID;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;

/**
 * Outbound port for claim persistence.
 *
 * <p>The implementation lives in {@code adapter.out.persistence}; the application layer only knows
 * this interface, which keeps the state machine and the validation independent from JPA.
 *
 * <p>{@link Page}/{@link Pageable} are used directly (pragmatic "hexagonal-lite", blueprint §2.7):
 * they are a query abstraction, not a JPA type, and re-inventing pagination would add code without
 * adding value.
 */
public interface ClaimRepositoryPort {

  /**
   * Persists a new claim together with the audit entry of its opening transition.
   *
   * @param claim claim to insert, never {@code null}
   * @return the persisted claim, hydrated with the values generated by the database defaults
   */
  Claim create(Claim claim);

  /**
   * @param claimId identifier to look up
   * @return the claim, or empty when it does not exist
   */
  Optional<Claim> findById(UUID claimId);

  /**
   * @param claimNumber business key to check
   * @return {@code true} when the claim number is already taken
   */
  boolean existsByClaimNumber(String claimNumber);

  /**
   * @param status optional status filter, {@code null} means "all statuses"
   * @param pageable page request
   * @return the matching page of claims
   */
  Page<Claim> findPage(ClaimStatus status, Pageable pageable);

  /**
   * @param claimId claim whose audit trail is requested
   * @return the transitions in chronological order
   */
  List<ClaimStatusHistory> findStatusHistory(UUID claimId);

  /**
   * Applies a status change and appends the corresponding audit entry.
   *
   * @param claim the claim as currently known by the application (source state of the transition)
   * @param targetStatus state to move to
   * @param note optional reason, may be {@code null}
   * @return the updated claim
   */
  Claim updateStatus(Claim claim, ClaimStatus targetStatus, String note);
}
