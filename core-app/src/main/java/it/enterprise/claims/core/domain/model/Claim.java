package it.enterprise.claims.core.domain.model;

import java.time.LocalDate;
import java.time.OffsetDateTime;
import java.util.List;
import java.util.Objects;
import java.util.UUID;

/**
 * A claim (pratica assicurativa) - the aggregate root of this service.
 *
 * <p>Pure domain type: it carries no JPA annotation and no JSON annotation. The persistence adapter
 * translates {@code ClaimJpaEntity} into this record and the web layer translates it into {@code
 * ClaimResponse}, so neither the database model nor the API model can leak into the other.
 *
 * <p>{@code policyNumber} and {@code customerId} are denormalised values resolved by the repository
 * adapter from the referenced policy, because the API contract exposes them on the claim resource.
 *
 * @param id database identifier, generated in the application layer
 * @param claimNumber human readable business key, unique per policy portfolio
 * @param policyId identifier of the policy the claim belongs to
 * @param policyNumber business key of that policy
 * @param customerId owner of the policy (resolved, not stored on the claim row)
 * @param claimType free classification of the claim (e.g. {@code CAR_DAMAGE})
 * @param status current lifecycle state
 * @param description free-text description, may be {@code null}
 * @param incidentDate date the incident happened
 * @param openedAt timestamp the claim was opened
 * @param updatedAt timestamp of the last modification
 * @param documentIds document-service ids attached to this claim, never {@code null}
 */
public record Claim(
    UUID id,
    String claimNumber,
    UUID policyId,
    String policyNumber,
    UUID customerId,
    String claimType,
    ClaimStatus status,
    String description,
    LocalDate incidentDate,
    OffsetDateTime openedAt,
    OffsetDateTime updatedAt,
    List<UUID> documentIds) {

  /** Compact constructor: enforces the invariants the database also enforces. */
  public Claim {
    Objects.requireNonNull(id, "id is required");
    Objects.requireNonNull(claimNumber, "claimNumber is required");
    Objects.requireNonNull(policyId, "policyId is required");
    Objects.requireNonNull(claimType, "claimType is required");
    Objects.requireNonNull(status, "status is required");
    Objects.requireNonNull(incidentDate, "incidentDate is required");
    Objects.requireNonNull(openedAt, "openedAt is required");
    documentIds = documentIds == null ? List.of() : List.copyOf(documentIds);
  }

  /**
   * Creates a brand new claim in {@link ClaimStatus#DRAFT}.
   *
   * @param id identifier generated by the application
   * @param claimNumber business key generated by the application
   * @param policyId policy the claim refers to
   * @param policyNumber business key of that policy
   * @param customerId owner of the policy
   * @param claimType classification of the claim
   * @param description free-text description, may be {@code null}
   * @param incidentDate date of the incident
   * @param openedAt opening timestamp
   * @return a claim in {@code DRAFT} with no documents attached
   */
  public static Claim opened(
      UUID id,
      String claimNumber,
      UUID policyId,
      String policyNumber,
      UUID customerId,
      String claimType,
      String description,
      LocalDate incidentDate,
      OffsetDateTime openedAt) {
    return new Claim(
        id,
        claimNumber,
        policyId,
        policyNumber,
        customerId,
        claimType,
        ClaimStatus.DRAFT,
        description,
        incidentDate,
        openedAt,
        openedAt,
        List.of());
  }

  /**
   * @param target requested target state, may be {@code null}
   * @return {@code true} when the state machine allows the transition
   */
  public boolean canTransitionTo(ClaimStatus target) {
    return status.canTransitionTo(target);
  }

  /**
   * @param newStatus state to move to
   * @param when timestamp of the change
   * @return a copy of this claim in the new state
   */
  public Claim withStatus(ClaimStatus newStatus, OffsetDateTime when) {
    return new Claim(
        id,
        claimNumber,
        policyId,
        policyNumber,
        customerId,
        claimType,
        newStatus,
        description,
        incidentDate,
        openedAt,
        when,
        documentIds);
  }

  /**
   * @param newDocumentIds full list of attached document ids
   * @return a copy of this claim with the given document ids
   */
  public Claim withDocumentIds(List<UUID> newDocumentIds) {
    return new Claim(
        id,
        claimNumber,
        policyId,
        policyNumber,
        customerId,
        claimType,
        status,
        description,
        incidentDate,
        openedAt,
        updatedAt,
        newDocumentIds);
  }
}
